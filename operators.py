a = 10
b = 5

print("Addition:", a + b)
print("Subtraction:", a - b)
print("Multiplication:", a * b)
print("Division:", a / b)
print("Modulus:", a % b)

print("a > b:", a > b)
print("a < b:", a < b)
print("a == b:", a == b)

print("Both conditions:", a > 5 and b > 2)
print("At least one:", a > 20 or b > 2)
print("Not equal:", not a == b)